require('./register-ts.cjs');
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { createWorkspaceStore } = require('../src/services/workspace-store.ts');
const { can } = require('../src/lib/permissions.ts');
test('folder projects enforce ownership, live access, explicit denials and archive restrictions', async t => {
 const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'folder-projects-'));
 t.after(() => fs.rm(directory, { recursive:true, force:true }));
 const store = createWorkspaceStore(directory,{username:'admin',password:'bootstrap-secret'});
 const {user:admin} = await store.authenticate('admin','bootstrap-secret','admin');
 const make = async username => store.createUser(admin,{username,name:username,password:'long-enough-password',role:'user'});
 const owner = await make('owner'); const reader = await make('reader'); const stranger = await make('stranger');
 const login = await store.authenticate('reader','long-enough-password','reader');
 const project = await store.createFolderProject(owner,{name:'Equipo',folderPath:'Proyectos/Equipo'});
 const ownerLink = await store.createShareLink(owner,{itemId:Buffer.from('Proyectos/Equipo/a.pdf').toString('base64url'),itemName:'a.pdf'});
 assert.ok(await store.getShareLink(ownerLink.id));
 assert.equal(project.ownerId,owner.id); assert.equal(project.role,'owner');
 await assert.rejects(store.updateFolderProject(stranger,{id:project.id,access:[]}),/propietario|administrador/i);
 await assert.rejects(store.updateFolderProject({...stranger,role:'admin'},{id:project.id,access:[]}),/propietario|administrador/i);
 await assert.rejects(store.createFolderProject(owner,{name:'Unsafe',folderPath:'../outside'}));
 await assert.rejects(store.createFolderProject(owner,{name:'Unsafe',folderPath:'Proyectos/Safe',ownerId:stranger.id}));
 await store.updateFolderProject(owner,{id:project.id,access:[{userId:reader.id,role:'reader'}]});
 let session = await store.getSession(login.token);
 assert.equal(can(session,'read','Proyectos/Equipo/a.pdf'),true);
 assert.equal(can(session,'upload','Proyectos/Equipo/a.pdf'),false);
 assert.equal((await store.listFolderProjects(reader))[0].members.length,0);
 await store.updateFolderProject(owner,{id:project.id,access:[{userId:reader.id,role:'editor'}]});
 session = await store.getSession(login.token); assert.equal(can(session,'upload','Proyectos/Equipo/a.pdf'),true);
 assert.equal(can(session,'share','Proyectos/Equipo/a.pdf'),false);
 await store.updateFolderProject(owner,{id:project.id,status:'archived'});
 session = await store.getSession(login.token); assert.equal(can(session,'download','Proyectos/Equipo/a.pdf'),true); assert.equal(can(session,'upload','Proyectos/Equipo/a.pdf'),false);
 assert.equal(await store.getShareLink(ownerLink.id),null);
 await store.updateFolderProject(owner,{id:project.id,status:'active',access:[]});
 session = await store.getSession(login.token); assert.equal(can(session,'read','Proyectos/Equipo/a.pdf'),false);
 assert.equal((await store.listFolderProjects(admin)).length,1);
 assert.equal((await store.listFolderProjects(stranger)).length,0);
 await store.updateFolderProject(owner,{id:project.id,access:[{userId:reader.id,role:'editor'}]});
 await store.updateUser(admin,reader.id,{grants:[{path:'Proyectos/Equipo',permissions:[]}]});
 session = await store.getSession(login.token); assert.equal(can(session,'read','Proyectos/Equipo/a.pdf'),false);
 const persisted = JSON.parse(await fs.readFile(path.join(directory,'workspace.json'),'utf8'));
 assert.ok(persisted.tasks.length); assert.ok(persisted.checks.length); assert.ok(persisted.sessions); assert.equal(persisted.shareLinks[0].id,ownerLink.id);
 assert.equal(JSON.stringify(await store.folderProjectPeople(owner)).includes('password'),false);
});

